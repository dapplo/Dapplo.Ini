using Dapplo.Ini.Configuration;

namespace Dapplo.Ini.Interfaces;

/// <summary>
/// Drafts: detached copies of a section for edit dialogs. The dialog binds to the draft and sees every change at once
/// (bindings, validation, previews), while the rest of the application keeps seeing the live section until the draft
/// is applied. A draft is never registered, saved, auto-saved or reloaded, and no lifecycle hook runs for it.
/// </summary>
/// <remarks>
/// <para>Create, edit and apply a draft on one thread (normally the UI thread). A draft is not meant to be shared between threads.</para>
/// <para>A draft holds no reference from the live section to itself (no event subscriptions): to cancel, simply drop it.</para>
/// </remarks>
public static class IniSectionDraftExtensions
{
    /// <summary>
    /// Creates a draft of <paramref name="section"/>: a new instance of the same generated class with a copy of every
    /// value (collections are copied, so changing a list in place on the draft doesn't touch the live section), the same
    /// metadata, value origins and protections (<see cref="IIniSection.IsConstant"/> and policy locks answer the same,
    /// and writing a locked key throws), and its own <c>PropertyChanging</c> / <c>PropertyChanged</c> and
    /// <c>INotifyDataErrorInfo</c>.
    /// </summary>
    /// <typeparam name="T">The section interface (or <see cref="IIniSection"/> when only that is known).</typeparam>
    /// <param name="section">The live section.</param>
    /// <returns>The draft, of the same type as <paramref name="section"/>.</returns>
    /// <exception cref="NotSupportedException">The section is not generated by Dapplo.Ini.Generator.</exception>
    public static T CreateDraft<T>(this T section) where T : class, IIniSection
    {
        if (section is null) throw new ArgumentNullException(nameof(section));
        return (T)(object)AsBase(section, nameof(section)).CreateDraftCore();
    }

    /// <summary><c>true</c> when <paramref name="section"/> is a draft created with <see cref="CreateDraft{T}"/>.</summary>
    public static bool IsDraft(this IIniSection section)
        => section is IniSectionBase { IsDraft: true };

    /// <summary>The section the draft was created from, or <c>null</c> when <paramref name="section"/> is not a draft.</summary>
    public static IIniSection? GetDraftSource(this IIniSection section)
        => (section as IniSectionBase)?.DraftSource;

    /// <summary>
    /// The keys that applying the draft would write now: keys that were assigned on the draft (or collections changed
    /// in place) and whose value differs from the base value, the live value when the draft was created.
    /// Use it e.g. to enable an OK or Apply button.
    /// </summary>
    /// <exception cref="InvalidOperationException"><paramref name="draft"/> is not a draft.</exception>
    public static IReadOnlyList<string> GetDraftChanges(this IIniSection draft)
        => AsBase(draft, nameof(draft)).GetDraftChangesCore();

    /// <summary>The keys that were assigned on the draft since it was created (or last applied or refreshed), changed or not.</summary>
    /// <exception cref="InvalidOperationException"><paramref name="draft"/> is not a draft.</exception>
    public static IReadOnlyCollection<string> GetDraftAssignedKeys(this IIniSection draft)
        => AsBase(draft, nameof(draft)).GetDraftAssignedKeysCore();

    /// <summary>
    /// The base value of <paramref name="key"/>: the value of the live section when the draft was created (or last
    /// applied or refreshed), as <see cref="IIniSection.GetValue(string)"/> returns it.
    /// </summary>
    /// <exception cref="InvalidOperationException"><paramref name="draft"/> is not a draft.</exception>
    public static object? GetDraftBaseValue(this IIniSection draft, string key)
        => AsBase(draft, nameof(draft)).GetDraftBaseValueCore(key);

    /// <summary>
    /// Applies the draft to the section it was created from. See <see cref="ApplyTo"/>; to apply several drafts and
    /// save once, use <see cref="IniConfig.Apply(IIniSection[])"/>.
    /// </summary>
    /// <returns>The keys that were written.</returns>
    public static IReadOnlyList<string> ApplyDraft(this IIniSection draft)
    {
        var draftBase = AsBase(draft, nameof(draft));
        var source = draftBase.DraftSource
                     ?? throw new InvalidOperationException($"The section '{draft.SectionName}' is not a draft. Create one with CreateDraft().");
        return draftBase.ApplyDraftTo(source);
    }

    /// <summary>
    /// Writes the changes of the draft to <paramref name="target"/> (normally the section it was created from):
    /// <list type="bullet">
    /// <item>Only keys that were assigned on the draft (or collections changed in place) and differ from the base value are written.</item>
    /// <item>Such a key is written even when the live value changed in the meantime: the user edited it. Keys the user
    /// didn't touch are never written, so runtime state changed while the dialog was open (e.g. a counter) stays.</item>
    /// <item>The values are written through the normal setters: <c>PropertyChanged</c>, the dirty flag, validation and
    /// protections behave as for any other write. All locks are checked before anything is written.</item>
    /// <item>When the section is <see cref="ITransactional"/> (and not already in a transaction), the writes are wrapped in
    /// <see cref="ITransactional.Begin"/> / <see cref="ITransactional.Commit"/>, so readers see the transactional
    /// properties switch at once.</item>
    /// </list>
    /// The written values become the new base values: the draft stays usable (e.g. for an Apply button).
    /// The section is not saved; the owning configuration saves it as usual (or use <see cref="IniConfig.Apply(IIniSection[])"/>).
    /// </summary>
    /// <param name="draft">The draft.</param>
    /// <param name="target">The live section, of the same generated type.</param>
    /// <returns>The keys that were written.</returns>
    /// <exception cref="InvalidOperationException"><paramref name="draft"/> is not a draft.</exception>
    /// <exception cref="ArgumentException"><paramref name="target"/> is not of the same type.</exception>
    /// <exception cref="AccessViolationException">A key to write is protected in <paramref name="target"/> (nothing was written).</exception>
    public static IReadOnlyList<string> ApplyTo(this IIniSection draft, IIniSection target)
        => AsBase(draft, nameof(draft)).ApplyDraftTo(target);

    /// <summary>
    /// Takes over the current live values for every key that was not assigned (nor changed in place) on the draft,
    /// e.g. when a dialog stays open for a long time, and raises <c>PropertyChanged</c> on the draft for each key that
    /// changes. The protections (constants, policies) are taken over from the live section too.
    /// </summary>
    /// <returns>The keys whose value changed.</returns>
    /// <exception cref="InvalidOperationException"><paramref name="draft"/> is not a draft.</exception>
    public static IReadOnlyList<string> RefreshDraft(this IIniSection draft)
        => AsBase(draft, nameof(draft)).RefreshDraftCore();

    private static IniSectionBase AsBase(IIniSection section, string paramName)
    {
        if (section is null) throw new ArgumentNullException(paramName);
        return section as IniSectionBase
               ?? throw new NotSupportedException($"The section '{section.SectionName}' ({section.GetType().Name}) does not support drafts: only sections generated by Dapplo.Ini.Generator do.");
    }
}
